function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').trim();
}

function tokens(s: string | null): string[] {
  if (!s) return [];
  return s
    .split(/[/,;|]+/)
    .map(normalize)
    .filter(Boolean);
}

/**
 * Возвращает регион по городу/стране. Город проверяется раньше страны —
 * он надёжнее. Для строк с несколькими местами берётся первый распознанный
 * токен (как правило, основное место жительства идёт первым).
 */
export function resolveRegion(city: string | null, country: string | null): Region | null {
  for (const t of [...tokens(city), ...tokens(country)]) {
    const r = PLACE_REGION[t];
    if (r) return r;
  }
  return null;
}
